# -*- coding: utf-8 -*-
"""One-shot: regenerate every analysis + figure, then dump the paper-ready
numbers (LaTeX table bodies + the sentences that carry a number) to
FINAL_NUMBERS.md. Run manually any time, or automatically when run_queue's
job list empties.

    python -m pcr_experiment.finalize
"""
import json, os, subprocess, sys, io
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(ROOT)
PY = sys.executable
OUT = os.path.join(ROOT, "FINAL_NUMBERS.md")


def sh(mod, *extra):
    subprocess.run([PY, "-m", f"pcr_experiment.{mod}", *extra], cwd=REPO,
                   capture_output=True, text=True, timeout=1800)


RESULTS_PAIRS = "pair3,pair7,pair10,pair11"  # the consistent 4-pair grid


def main():
    # 1. rebuild everything from checkpoints (no API)
    for m in ("pooled_analysis", "family_significance", "cost_latency_analysis",
              "ablation_study", "trade_off_figures", "make_figures"):
        extra = ["--export"] if m in ("pooled_analysis", "family_significance",
                                      "cost_latency_analysis", "ablation_study") else []
        if m == "family_significance":
            extra += ["--only-pairs", RESULTS_PAIRS]
        try:
            sh(m, *extra)
        except Exception as e:
            print(f"  warn: {m} failed ({e})")

    exp = os.path.join(ROOT, "exports")
    fam = json.load(open(os.path.join(exp, "family_significance.json"), encoding="utf-8"))
    abl = json.load(open(os.path.join(exp, "ablation_study.json"), encoding="utf-8"))

    buf = io.StringIO()
    w = buf.write
    w(f"# PCR --- final numbers  ({datetime.now(timezone.utc):%Y-%m-%d %H:%MZ})\n\n")
    w("Auto-generated by `finalize.py`. Paste the LaTeX blocks into "
      "`pcr_ieee_v2.tex`, replacing the same-named table body.\n\n")

    # --- grid table (from gen_grid_table) ---
    w("## Table `tab:percell` --- full grid (C-Hall then Agreement)\n\n```latex\n")
    g = subprocess.run([PY, os.path.join(ROOT, "gen_grid_table.py")], cwd=REPO,
                       capture_output=True, text=True)
    w(g.stdout)
    w("```\n\n")

    # --- family table body ---
    w("## Table `tab:family` --- within minus cross gap\n\n```latex\n")
    def frow(bm, m):
        v = fam["per_benchmark"].get(bm, {}).get(m)
        if not v:
            return None
        lo, hi = v["ci95"]
        star = "^\\ast" if (lo > 0 or hi < 0) else ""
        return (f"{bm} & {v['within']*100:.1f} & {v['cross']*100:.1f} & "
                f"${v['gap']*100:+.1f}$ & $[{lo*100:+.1f},{hi*100:+.1f}]{star}$ \\\\")
    order = ["arc", "openbookqa", "mmlu", "commonsenseqa", "truthfulqa", "mmlu_pro", "gsm8k"]
    for metric, title in (("agreement", "Agreement rate"), ("c_hall", "Coordinated hallucination")):
        w(f"\\multicolumn{{5}}{{l}}{{\\textit{{{title}}}}} \\\\\n\\midrule\n")
        for bm in order:
            r = frow(bm, metric)
            if r:
                w(r + "\n")
        b = fam["benchmark_balanced"].get(metric, {})
        if b:
            lo, hi = b["ci95"]
            star = "^\\ast" if (lo > 0 or hi < 0) else ""
            w(f"\\textit{{balanced (pair-level)}} & {b['within']*100:.1f} & "
              f"{b['cross']*100:.1f} & ${b['gap']*100:+.1f}$ & "
              f"$[{lo*100:+.1f},{hi*100:+.1f}]{star}$ \\\\\n\\midrule\n")
    w("```\n\n")

    # --- policy tier table ---
    w("## Table `tab:policytier` --- policy ablation by tier\n\n```latex\n")
    TIER = {"arc": "easy", "openbookqa": "easy", "commonsenseqa": "easy",
            "mmlu": "medium", "mmlu_pro": "hard", "truthfulqa": "hard", "gsm8k": "math"}
    rows = []
    for key, cell in abl.items():
        if key.startswith("pcr3"):
            continue
        pair, bm = key.rsplit("_", 1)
        # rsplit fails for mmlu_pro -> handle
        for b in ("mmlu_pro", "openbookqa", "commonsenseqa", "truthfulqa", "gsm8k", "mmlu", "arc"):
            if key.endswith("_" + b):
                pair, bm = key[:-(len(b) + 1)], b
                break
        acc = cell.get("acc", {})
        rows.append((TIER.get(bm, "?"), pair, bm,
                     acc.get("pcr2"), acc.get("best_cheap"), acc.get("always_frontier"),
                     cell.get("chall", {}).get("pcr2"), cell.get("escalation_rate")))
    for t in ("easy", "medium", "hard", "math"):
        for tier, pair, bm, p2, bc, af, ch, esc in sorted(r for r in rows if r[0] == t):
            def f(x, pct=False):
                return "---" if x is None else (f"{x*100:.1f}" if not pct else f"{x*100:.1f}")
            w(f"{tier} & {pair} ({bm}) & {f(p2)} & {f(bc)} & {f(af)} & "
              f"{f(ch)} & {f(esc)} \\\\\n")
    w("```\n\n")

    # --- key sentences with numbers ---
    bb = fam["benchmark_balanced"]
    w("## Sentences to re-check in the prose\n\n")
    w(f"- Family, C-Hall balanced gap: **{bb['c_hall']['gap']*100:+.1f} pp**, "
      f"CI [{bb['c_hall']['ci95'][0]*100:+.1f}, {bb['c_hall']['ci95'][1]*100:+.1f}]\n")
    w(f"- Family, agreement balanced gap: **{bb['agreement']['gap']*100:+.1f} pp**, "
      f"CI [{bb['agreement']['ci95'][0]*100:+.1f}, {bb['agreement']['ci95'][1]*100:+.1f}]\n")
    gs = fam["per_benchmark"].get("gsm8k", {}).get("c_hall", {})
    if gs:
        w(f"- Family, GSM8K C-Hall gap: **{gs['gap']*100:+.1f} pp**, "
          f"CI [{gs['ci95'][0]*100:+.1f}, {gs['ci95'][1]*100:+.1f}]\n")
    w(f"- Cells in family pool: **{len(fam.get('cells_used', []))}**\n")

    open(OUT, "w", encoding="utf-8").write(buf.getvalue())
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
